CREATE OR REPLACE VIEW STAGING.STG_STANDINGS AS
SELECT
    SEASON,
    TEAM_ID,
    TEAM_NAME,
    LADDER_RANK,
    PLAYED,
    WINS,
    LOSSES,
    DRAWS,
    PREMIERSHIP_POINTS,
    POINTS_FOR,
    POINTS_AGAINST,
    PERCENTAGE,
    GOALS_FOR,
    BEHINDS_FOR,
    GOALS_AGAINST,
    BEHINDS_AGAINST,
    LADDER_RANK <= 8 AS MADE_TOP_8
FROM RAW.STANDINGS
QUALIFY ROW_NUMBER() OVER (PARTITION BY SEASON, TEAM_ID ORDER BY LOADED_AT DESC) = 1;
