CREATE OR REPLACE VIEW STAGING.STG_GAMES AS
SELECT
    GAME_ID,
    SEASON,
    ROUND_NUMBER,
    ROUND_NAME,
    MATCH_DATETIME,
    MATCH_DATETIME::DATE AS MATCH_DATE,
    DAYNAME(MATCH_DATETIME) AS MATCH_DAY,
    TIMEZONE,
    VENUE,
    HOME_TEAM_ID,
    HOME_TEAM,
    AWAY_TEAM_ID,
    AWAY_TEAM,
    HOME_GOALS,
    HOME_BEHINDS,
    HOME_SCORE,
    AWAY_GOALS,
    AWAY_BEHINDS,
    AWAY_SCORE,
    HOME_SCORE + AWAY_SCORE AS TOTAL_SCORE,
    ABS(HOME_SCORE - AWAY_SCORE) AS WINNING_MARGIN,
    CASE
        WHEN HOME_SCORE > AWAY_SCORE THEN 'HOME'
        WHEN HOME_SCORE < AWAY_SCORE THEN 'AWAY'
        ELSE 'DRAW'
    END AS WINNING_SIDE,
    WINNER_TEAM_ID,
    WINNER,
    IS_FINAL,
    IS_GRAND_FINAL,
    IFF(IS_FINAL, 'Finals', 'Home and Away') AS SEASON_STAGE
FROM RAW.GAMES
QUALIFY ROW_NUMBER() OVER (PARTITION BY GAME_ID ORDER BY UPDATED_AT DESC, LOADED_AT DESC) = 1;
