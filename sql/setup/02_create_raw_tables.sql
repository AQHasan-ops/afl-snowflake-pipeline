CREATE TABLE IF NOT EXISTS AFL_DB.RAW.TEAMS (
    TEAM_ID         INTEGER,
    TEAM_NAME       VARCHAR,
    ABBREVIATION    VARCHAR,
    DEBUT_YEAR      INTEGER,
    RETIREMENT_YEAR INTEGER,
    LOGO_URL        VARCHAR,
    LOADED_AT       TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS AFL_DB.RAW.GAMES (
    GAME_ID         INTEGER,
    SEASON          INTEGER,
    ROUND_NUMBER    INTEGER,
    ROUND_NAME      VARCHAR,
    MATCH_DATETIME  TIMESTAMP_NTZ,
    TIMEZONE        VARCHAR,
    VENUE           VARCHAR,
    HOME_TEAM_ID    INTEGER,
    HOME_TEAM       VARCHAR,
    AWAY_TEAM_ID    INTEGER,
    AWAY_TEAM       VARCHAR,
    HOME_GOALS      INTEGER,
    HOME_BEHINDS    INTEGER,
    HOME_SCORE      INTEGER,
    AWAY_GOALS      INTEGER,
    AWAY_BEHINDS    INTEGER,
    AWAY_SCORE      INTEGER,
    WINNER_TEAM_ID  INTEGER,
    WINNER          VARCHAR,
    IS_FINAL        BOOLEAN,
    IS_GRAND_FINAL  BOOLEAN,
    UPDATED_AT      TIMESTAMP_NTZ,
    LOADED_AT       TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS AFL_DB.RAW.STANDINGS (
    SEASON              INTEGER,
    TEAM_ID             INTEGER,
    TEAM_NAME           VARCHAR,
    LADDER_RANK         INTEGER,
    PLAYED              INTEGER,
    WINS                INTEGER,
    LOSSES              INTEGER,
    DRAWS               INTEGER,
    PREMIERSHIP_POINTS  INTEGER,
    POINTS_FOR          INTEGER,
    POINTS_AGAINST      INTEGER,
    PERCENTAGE          NUMBER(6, 2),
    GOALS_FOR           INTEGER,
    BEHINDS_FOR         INTEGER,
    GOALS_AGAINST       INTEGER,
    BEHINDS_AGAINST     INTEGER,
    LOADED_AT           TIMESTAMP_NTZ
);
