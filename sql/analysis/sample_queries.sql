SELECT SEASON, LADDER_RANK, TEAM_NAME, WINS, LOSSES, DRAWS, LADDER_PERCENTAGE, IS_PREMIER
FROM REPORTING.TEAM_SEASON_SUMMARY
WHERE SEASON = 2026
ORDER BY LADDER_RANK;

SELECT TEAM_NAME, SUM(WINS) AS TOTAL_WINS, ROUND(AVG(WIN_PCT), 1) AS AVG_WIN_PCT
FROM REPORTING.TEAM_SEASON_SUMMARY
GROUP BY TEAM_NAME
ORDER BY TOTAL_WINS DESC;

SELECT SEASON, TEAM_NAME, AVG_POINTS_FOR, AVG_POINTS_AGAINST, AVG_MARGIN
FROM REPORTING.TEAM_SEASON_SUMMARY
QUALIFY RANK() OVER (PARTITION BY SEASON ORDER BY AVG_POINTS_FOR DESC) <= 3
ORDER BY SEASON, AVG_POINTS_FOR DESC;

SELECT TEAM_NAME, ROUND_NAME, OPPONENT_NAME, RESULT, WINS_LAST_5, AVG_MARGIN_LAST_5
FROM REPORTING.TEAM_FORM
WHERE SEASON = 2026
QUALIFY ROW_NUMBER() OVER (PARTITION BY TEAM_ID ORDER BY GAME_NUMBER DESC) = 1
ORDER BY WINS_LAST_5 DESC, AVG_MARGIN_LAST_5 DESC;

SELECT VENUE, SUM(GAMES) AS GAMES, ROUND(AVG(AVG_TOTAL_SCORE), 1) AS AVG_TOTAL_SCORE, ROUND(AVG(HOME_WIN_PCT), 1) AS HOME_WIN_PCT
FROM REPORTING.VENUE_SUMMARY
GROUP BY VENUE
HAVING SUM(GAMES) >= 10
ORDER BY HOME_WIN_PCT DESC;
