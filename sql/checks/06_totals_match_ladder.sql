WITH home_and_away AS (
    SELECT
        SEASON,
        TEAM_ID,
        COUNT(*) AS PLAYED,
        COUNT_IF(RESULT = 'W') AS WINS,
        COUNT_IF(RESULT = 'L') AS LOSSES,
        COUNT_IF(RESULT = 'D') AS DRAWS,
        SUM(POINTS_FOR) AS POINTS_FOR,
        SUM(POINTS_AGAINST) AS POINTS_AGAINST
    FROM REPORTING.FCT_TEAM_GAMES
    WHERE SEASON_STAGE = 'Home and Away'
    GROUP BY SEASON, TEAM_ID
)

SELECT l.SEASON, l.TEAM_NAME
FROM STAGING.STG_STANDINGS l
LEFT JOIN home_and_away g
    ON l.SEASON = g.SEASON
    AND l.TEAM_ID = g.TEAM_ID
WHERE g.TEAM_ID IS NULL
   OR l.PLAYED <> g.PLAYED
   OR l.WINS <> g.WINS
   OR l.LOSSES <> g.LOSSES
   OR l.DRAWS <> g.DRAWS
   OR l.POINTS_FOR <> g.POINTS_FOR
   OR l.POINTS_AGAINST <> g.POINTS_AGAINST;
