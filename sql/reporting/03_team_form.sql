CREATE OR REPLACE TABLE REPORTING.TEAM_FORM AS
SELECT
    GAME_ID,
    SEASON,
    ROUND_NUMBER,
    ROUND_NAME,
    MATCH_DATE,
    TEAM_ID,
    TEAM_NAME,
    OPPONENT_NAME,
    IS_HOME,
    POINTS_FOR,
    POINTS_AGAINST,
    MARGIN,
    RESULT,
    ROW_NUMBER() OVER (
        PARTITION BY TEAM_ID, SEASON
        ORDER BY MATCH_DATE, GAME_ID
    ) AS GAME_NUMBER,
    SUM(IFF(RESULT = 'W', 1, 0)) OVER (
        PARTITION BY TEAM_ID, SEASON
        ORDER BY MATCH_DATE, GAME_ID
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS WINS_TO_DATE,
    SUM(IFF(RESULT = 'W', 1, 0)) OVER (
        PARTITION BY TEAM_ID, SEASON
        ORDER BY MATCH_DATE, GAME_ID
        ROWS BETWEEN 4 PRECEDING AND CURRENT ROW
    ) AS WINS_LAST_5,
    ROUND(AVG(MARGIN) OVER (
        PARTITION BY TEAM_ID, SEASON
        ORDER BY MATCH_DATE, GAME_ID
        ROWS BETWEEN 4 PRECEDING AND CURRENT ROW
    ), 1) AS AVG_MARGIN_LAST_5,
    LAG(RESULT) OVER (
        PARTITION BY TEAM_ID, SEASON
        ORDER BY MATCH_DATE, GAME_ID
    ) AS PREVIOUS_RESULT
FROM REPORTING.FCT_TEAM_GAMES;
