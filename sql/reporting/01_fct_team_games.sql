CREATE OR REPLACE TABLE REPORTING.FCT_TEAM_GAMES AS
WITH home_side AS (
    SELECT
        GAME_ID,
        SEASON,
        ROUND_NUMBER,
        ROUND_NAME,
        MATCH_DATE,
        VENUE,
        SEASON_STAGE,
        HOME_TEAM_ID AS TEAM_ID,
        HOME_TEAM AS TEAM_NAME,
        AWAY_TEAM_ID AS OPPONENT_ID,
        AWAY_TEAM AS OPPONENT_NAME,
        TRUE AS IS_HOME,
        HOME_GOALS AS GOALS,
        HOME_BEHINDS AS BEHINDS,
        HOME_SCORE AS POINTS_FOR,
        AWAY_SCORE AS POINTS_AGAINST
    FROM STAGING.STG_GAMES
),

away_side AS (
    SELECT
        GAME_ID,
        SEASON,
        ROUND_NUMBER,
        ROUND_NAME,
        MATCH_DATE,
        VENUE,
        SEASON_STAGE,
        AWAY_TEAM_ID AS TEAM_ID,
        AWAY_TEAM AS TEAM_NAME,
        HOME_TEAM_ID AS OPPONENT_ID,
        HOME_TEAM AS OPPONENT_NAME,
        FALSE AS IS_HOME,
        AWAY_GOALS AS GOALS,
        AWAY_BEHINDS AS BEHINDS,
        AWAY_SCORE AS POINTS_FOR,
        HOME_SCORE AS POINTS_AGAINST
    FROM STAGING.STG_GAMES
),

team_games AS (
    SELECT * FROM home_side
    UNION ALL
    SELECT * FROM away_side
)

SELECT
    *,
    POINTS_FOR - POINTS_AGAINST AS MARGIN,
    CASE
        WHEN POINTS_FOR > POINTS_AGAINST THEN 'W'
        WHEN POINTS_FOR < POINTS_AGAINST THEN 'L'
        ELSE 'D'
    END AS RESULT,
    ROUND(DIV0(GOALS, GOALS + BEHINDS) * 100, 1) AS ACCURACY_PCT
FROM team_games;
