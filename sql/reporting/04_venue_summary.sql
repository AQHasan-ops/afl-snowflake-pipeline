CREATE OR REPLACE TABLE REPORTING.VENUE_SUMMARY AS
SELECT
    SEASON,
    VENUE,
    COUNT(*) AS GAMES,
    ROUND(AVG(TOTAL_SCORE), 1) AS AVG_TOTAL_SCORE,
    MAX(TOTAL_SCORE) AS HIGHEST_TOTAL_SCORE,
    ROUND(AVG(WINNING_MARGIN), 1) AS AVG_WINNING_MARGIN,
    COUNT_IF(WINNING_SIDE = 'HOME') AS HOME_WINS,
    COUNT_IF(WINNING_SIDE = 'AWAY') AS AWAY_WINS,
    ROUND(DIV0(COUNT_IF(WINNING_SIDE = 'HOME'), COUNT(*)) * 100, 1) AS HOME_WIN_PCT
FROM STAGING.STG_GAMES
GROUP BY SEASON, VENUE
ORDER BY SEASON, GAMES DESC;
