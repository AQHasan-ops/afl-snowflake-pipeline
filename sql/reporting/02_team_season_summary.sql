CREATE OR REPLACE TABLE REPORTING.TEAM_SEASON_SUMMARY AS
WITH season_stats AS (
    SELECT
        SEASON,
        TEAM_ID,
        TEAM_NAME,
        COUNT(*) AS GAMES_PLAYED,
        COUNT_IF(RESULT = 'W') AS WINS,
        COUNT_IF(RESULT = 'L') AS LOSSES,
        COUNT_IF(RESULT = 'D') AS DRAWS,
        ROUND(DIV0(COUNT_IF(RESULT = 'W'), COUNT(*)) * 100, 1) AS WIN_PCT,
        SUM(POINTS_FOR) AS TOTAL_POINTS_FOR,
        SUM(POINTS_AGAINST) AS TOTAL_POINTS_AGAINST,
        ROUND(AVG(POINTS_FOR), 1) AS AVG_POINTS_FOR,
        ROUND(AVG(POINTS_AGAINST), 1) AS AVG_POINTS_AGAINST,
        ROUND(AVG(MARGIN), 1) AS AVG_MARGIN,
        ROUND(DIV0(SUM(GOALS), SUM(GOALS) + SUM(BEHINDS)) * 100, 1) AS ACCURACY_PCT,
        COUNT_IF(IS_HOME AND RESULT = 'W') AS HOME_WINS,
        COUNT_IF(NOT IS_HOME AND RESULT = 'W') AS AWAY_WINS,
        MAX(IFF(MARGIN > 0, MARGIN, NULL)) AS BIGGEST_WIN,
        MIN(IFF(MARGIN < 0, MARGIN, NULL)) AS BIGGEST_LOSS,
        COUNT_IF(SEASON_STAGE = 'Finals') AS FINALS_PLAYED,
        COUNT_IF(SEASON_STAGE = 'Finals' AND RESULT = 'W') AS FINALS_WON
    FROM REPORTING.FCT_TEAM_GAMES
    GROUP BY SEASON, TEAM_ID, TEAM_NAME
),

premiers AS (
    SELECT
        SEASON,
        WINNER_TEAM_ID AS TEAM_ID
    FROM STAGING.STG_GAMES
    WHERE IS_GRAND_FINAL
)

SELECT
    s.SEASON,
    s.TEAM_ID,
    s.TEAM_NAME,
    t.ABBREVIATION,
    l.LADDER_RANK,
    l.PREMIERSHIP_POINTS,
    l.PERCENTAGE AS LADDER_PERCENTAGE,
    COALESCE(l.MADE_TOP_8, FALSE) AS MADE_TOP_8,
    p.TEAM_ID IS NOT NULL AS IS_PREMIER,
    s.GAMES_PLAYED,
    s.WINS,
    s.LOSSES,
    s.DRAWS,
    s.WIN_PCT,
    s.TOTAL_POINTS_FOR,
    s.TOTAL_POINTS_AGAINST,
    s.AVG_POINTS_FOR,
    s.AVG_POINTS_AGAINST,
    s.AVG_MARGIN,
    s.ACCURACY_PCT,
    s.HOME_WINS,
    s.AWAY_WINS,
    s.BIGGEST_WIN,
    s.BIGGEST_LOSS,
    s.FINALS_PLAYED,
    s.FINALS_WON
FROM season_stats s
LEFT JOIN STAGING.STG_TEAMS t
    ON s.TEAM_ID = t.TEAM_ID
LEFT JOIN STAGING.STG_STANDINGS l
    ON s.SEASON = l.SEASON
    AND s.TEAM_ID = l.TEAM_ID
LEFT JOIN premiers p
    ON s.SEASON = p.SEASON
    AND s.TEAM_ID = p.TEAM_ID
ORDER BY s.SEASON, l.LADDER_RANK;
